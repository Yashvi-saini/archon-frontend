function hashSeed(input: string): number {
  let hash = 0;
  for (let i = 0; i < input.length; i++) {
    hash = (hash << 5) - hash + input.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function createComponentElements(
  item: SystemDesignComponentItem,
  x: number,
  y: number,
  customLabel?: string,
  fixedId?: string
): any[] {
  const shapeId = fixedId || `comp-${item.id}`;
  const labelId = `${shapeId}-lbl`;
  const groupId = `group-${shapeId}`;
  const displayLabel = customLabel || item.name;

  const shapeElement = {
    id: shapeId,
    type: item.shape,
    x,
    y,
    width: item.width,
    height: item.height,
    angle: 0,
    strokeColor: item.strokeColor,
    backgroundColor: item.bgColor,
    fillStyle: "solid",
    strokeWidth: 2,
    strokeStyle: "solid",
    roughness: 1,
    opacity: 100,
    groupIds: [groupId],
    frameId: null,
    index: null,
    roundness: item.shape === "rectangle" ? { type: 3 } : { type: 2 },
    seed: hashSeed(shapeId),
    version: 1,
    versionNonce: hashSeed(`${shapeId}-nonce`),
    isDeleted: false,
    boundElements: [{ id: labelId, type: "text" }],
    updated: 1,
    link: null,
    locked: false,
    customData: {
      componentType: item.type,
      componentId: item.id,
      label: displayLabel,
      category: item.category,
      isSystemDesignComponent: true,
    },
  };

  const labelElement = {
    id: labelId,
    type: "text",
    x: x + 8,
    y: y + item.height / 2 - 10,
    width: item.width - 16,
    height: 20,
    angle: 0,
    strokeColor: "#1e1e1e",
    backgroundColor: "transparent",
    fillStyle: "solid",
    strokeWidth: 1,
    strokeStyle: "solid",
    roughness: 0,
    opacity: 100,
    groupIds: [groupId],
    frameId: null,
    index: null,
    roundness: null,
    seed: hashSeed(labelId),
    version: 1,
    versionNonce: hashSeed(`${labelId}-nonce`),
    isDeleted: false,
    boundElements: null,
    updated: 1,
    link: null,
    locked: false,
    text: displayLabel,
    fontSize: 14,
    fontFamily: 1,
    textAlign: "center",
    verticalAlign: "middle",
    containerId: shapeId,
    originalText: displayLabel,
    autoResize: true,
    lineHeight: 1.25,
    customData: {
      parentComponentId: shapeId,
    },
  };

  return [shapeElement, labelElement];
}

